/**
 * Local Worker dev against PRODUCTION D1 data (remote bindings).
 *
 *   npm run dev:worker:remote      (then `npm run dev` in a second terminal)
 *
 * The Worker code runs locally (fast reloads, local secrets from .dev.vars);
 * only the D1 binding is proxied to the real database. wrangler.toml stays the
 * single config source: this script copies it with `remote = true` added to the
 * top-level D1 binding and runs `wrangler dev` with that temporary copy.
 *
 * WARNING: writes (admin edits, likes, submissions, feedback) hit production.
 * Requires `wrangler login`.
 */
import { spawn } from 'node:child_process';
import { readFileSync, writeFileSync, unlinkSync, existsSync } from 'node:fs';

const SOURCE = 'wrangler.toml';
// Kept next to wrangler.toml so relative paths (main, assets, .dev.vars) resolve the same.
const TEMP = 'wrangler.remote-data.toml';

const toml = readFileSync(SOURCE, 'utf8');
const d1Block = /(\[\[d1_databases\]\][\s\S]*?database_id\s*=\s*"[^"]+")/;
if (!d1Block.test(toml)) {
  console.error(`Could not find the [[d1_databases]] binding in ${SOURCE}.`);
  process.exit(1);
}
writeFileSync(
  TEMP,
  `# GENERATED by scripts/dev-remote.mjs — do not edit or commit.\n${toml.replace(d1Block, '$1\nremote = true')}`,
);

console.warn('\n⚠️  DB = PRODUCTION D1. Any write made in this session changes live data.\n');

const cleanup = () => {
  if (existsSync(TEMP)) unlinkSync(TEMP);
};
const child = spawn('npx', ['wrangler', 'dev', '--config', TEMP, ...process.argv.slice(2)], {
  stdio: 'inherit',
  shell: true,
});
for (const signal of ['SIGINT', 'SIGTERM']) {
  process.on(signal, () => child.kill(signal));
}
child.on('exit', (code) => {
  cleanup();
  process.exit(code ?? 0);
});
